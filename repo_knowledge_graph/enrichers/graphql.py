"""
GraphQL APIs: Netflix DGS and Spring for GraphQL.

- Schema files (`*.graphqls`, `*.graphql`, `*.gqls`): types, fields, arguments and return types.
- Resolvers: @DgsQuery / @DgsMutation / @DgsSubscription / @DgsData (DGS) and @QueryMapping /
  @MutationMapping / @SubscriptionMapping / @SchemaMapping / @BatchMapping (Spring for GraphQL).
  Constants generated by the DGS codegen (`MUTATION.CreateArticle`, `QUERY.TYPE_NAME`,
  `DgsConstants.QUERY_TYPE`), absent from the repository, are resolved against the schema.

Root operations (Query, Mutation, Subscription) become `endpoint` nodes (`endpoint:GRAPHQL Query.article`,
`http_method: "GRAPHQL"`) with `handled_by` edges, arguments, return type, security and the filter-chain
rule of the GraphQL path; schema operations without resolver get `implemented: false`. Every resolver
method gets `attributes['graphql'] = {type, field, root}` (field resolvers such as `Article.author` too).
"""
import logging
import re
from typing import Any, Dict, List, Optional, Tuple

from .base import EnrichmentContext, annotation, annotation_value
from .spring_config import property_value
from .spring_web import SECURITY_ANNOTATIONS, ant_matches, security_rules

logger = logging.getLogger(__name__)

SCHEMA_EXTENSIONS = ('.graphqls', '.graphql', '.gqls')
ROOT_TYPES = ('Query', 'Mutation', 'Subscription')
RESOLVERS = {
    'DgsQuery': 'Query', 'DgsMutation': 'Mutation', 'DgsSubscription': 'Subscription', 'DgsData': None,
    'QueryMapping': 'Query', 'MutationMapping': 'Mutation', 'SubscriptionMapping': 'Subscription',
    'SchemaMapping': None, 'BatchMapping': None,
}
_TYPE_BLOCK = re.compile(r'(?:extend\s+)?(?:type|interface)\s+(\w+)[^{]*\{(.*?)\}', re.S)
_FIELD = re.compile(r'(\w+)\s*(?:\(([^)]*)\))?\s*:\s*([\w\[\]!]+)', re.S)


def applies(context: EnrichmentContext) -> bool:
    if any(True for _ in context.files(*SCHEMA_EXTENSIONS)):
        return True
    return any({a.get('name') for a in (e.get('attributes') or {}).get('annotations') or []} & set(RESOLVERS)
               for _, e in context.java_declarations())


def parse_schema(content: str) -> Dict[str, Dict[str, Dict[str, Any]]]:
    """type -> field -> {args: [{name, type}], returns, description}."""
    content = re.sub(r'"""(.*?)"""', lambda m: '#' + ' '.join(m.group(1).split()), content, flags=re.S)
    types: Dict[str, Dict[str, Dict[str, Any]]] = {}
    for match in _TYPE_BLOCK.finditer(content):
        type_name, body = match.group(1), match.group(2)
        fields = types.setdefault(type_name, {})
        # Comment / docstring lines describe the next field: remember them by line offset
        description: Optional[str] = None
        kept: List[str] = []
        descriptions: Dict[int, Optional[str]] = {}
        offset = 0
        for line in body.split('\n'):
            stripped = line.strip()
            if stripped.startswith('#'):
                description = stripped.lstrip('#').strip() or description
                continue
            code = re.sub(r'#.*$', '', line)
            descriptions[offset] = description
            kept.append(code)
            offset += len(code) + 1
            if stripped:
                description = None
        joined = '\n'.join(kept)
        for field in _FIELD.finditer(joined):
            args = []
            for arg in re.split(r'[,\n]', field.group(2) or ''):
                arg_match = re.match(r'\s*(\w+)\s*:\s*([\w\[\]!]+)', arg)
                if arg_match:
                    args.append({'name': arg_match.group(1), 'type': arg_match.group(2)})
            line_start = joined.rfind('\n', 0, field.start()) + 1
            fields[field.group(1)] = {'args': args, 'returns': field.group(3),
                                      'description': descriptions.get(line_start)}
    return types


def _decapitalize(name: str) -> str:
    return name[:1].lower() + name[1:]


class GraphQLEnricher:
    def __init__(self, context: EnrichmentContext):
        self.context = context
        self.schema: Dict[str, Dict[str, Dict[str, Any]]] = {}
        self.schema_files: Dict[Tuple[str, str], str] = {}
        for path, content in context.files(*SCHEMA_EXTENSIONS):
            for type_name, fields in parse_schema(content).items():
                self.schema.setdefault(type_name, {}).update(fields)
                for field in fields:
                    self.schema_files[(type_name, field)] = path
        self.types_upper = {t.upper(): t for t in self.schema}
        self.types_upper.update({t.upper(): t for t in ROOT_TYPES})

    def resolve_type(self, value: Any, default: Optional[str]) -> Optional[str]:
        """'{{MUTATION.TYPE_NAME}}', '{{DgsConstants.QUERY_TYPE}}', 'Article' -> schema type name."""
        if value is None:
            return default
        text = str(value)
        if text.startswith('{{'):
            reference = text.strip('{}')
            head, _, tail = reference.rpartition('.')
            if tail.endswith('_TYPE'):  # DgsConstants.QUERY_TYPE
                return self.types_upper.get(tail[:-len('_TYPE')], default)
            if tail == 'TYPE_NAME':  # ARTICLE.TYPE_NAME
                return self.types_upper.get(head.rsplit('.', 1)[-1], default)
            return default
        return text or default

    def resolve_field(self, value: Any, type_name: Optional[str], method_name: str) -> str:
        """'{{QUERY.Article}}' -> 'article' (DGS codegen constant), checked against the schema."""
        if value is None:
            candidate = method_name
        else:
            text = str(value)
            candidate = _decapitalize(text.strip('{}').rsplit('.', 1)[-1]) if text.startswith('{{') else text
        fields = self.schema.get(type_name or '', {})
        if candidate not in fields:
            lowered = {f.lower(): f for f in fields}
            candidate = lowered.get(candidate.lower(), candidate)
        return candidate

    def resolvers(self) -> List[Tuple[str, Dict[str, Any], str, str]]:
        """(path, entity, type, field) of every resolver method."""
        found = []
        for path, entity in self.context.java_declarations():
            if entity.get('type') not in ('method', 'api_endpoint'):
                continue
            attributes = entity.get('attributes') or {}
            for item in attributes.get('annotations') or []:
                name = item.get('name')
                if name not in RESOLVERS:
                    continue
                method_name = entity['name'].rsplit('::', 1)[-1]
                owner = (self.context.java_types.get(entity['name'].split('::', 1)[0]) or {}).get('attributes') or {}
                class_type = annotation_value(annotation(owner, 'SchemaMapping'), 'typeName')
                default_type = RESOLVERS[name] or (str(class_type) if class_type else None)
                type_name = self.resolve_type(annotation_value(item, 'parentType', 'typeName'), default_type)
                field = self.resolve_field(annotation_value(item, 'field', 'value', 'name'), type_name, method_name)
                if type_name:
                    found.append((path, entity, type_name, field))
                break
        return found

    def graphql_path(self) -> str:
        config = self.context.shared.get('config') or {}
        return (property_value(config, 'spring.graphql.path') or property_value(config, 'dgs.graphql.path')
                or '/graphql')

    def security(self, attributes: Dict[str, Any], owner: Dict[str, Any]) -> List[Dict[str, Any]]:
        rules = []
        for level, attrs in (('method', attributes), ('class', owner)):
            for item in attrs.get('annotations') or []:
                if item.get('name') in SECURITY_ANNOTATIONS:
                    rules.append({'annotation': item['name'], 'value': annotation_value(item, 'value'),
                                  'level': level})
        return rules

    def filter_chain(self, path: str) -> Optional[Dict[str, Any]]:
        for rule in security_rules(self.context):
            if rule.get('http_method') in (None, 'POST') and any(ant_matches(p, path) for p in rule['patterns']):
                return {'rule': rule['rule'], 'args': rule['args'], 'patterns': rule['patterns'],
                        'file': rule['file'], 'line': rule['line'], 'confidence': 'inferred'}
        return None

    def run(self) -> None:
        context = self.context
        http_path = self.graphql_path()
        chain = self.filter_chain(http_path)
        implemented = set()
        operations = 0
        for path, entity, type_name, field in self.resolvers():
            handler = context.registry.lookup(entity['name'])
            if not handler:
                continue
            root = type_name in ROOT_TYPES
            context.framework_attributes(handler, 'graphql').update({'type': type_name, 'field': field, 'root': root})
            if not root:
                continue
            implemented.add((type_name, field))
            schema_field = self.schema.get(type_name, {}).get(field, {})
            attributes = entity.get('attributes') or {}
            owner = (context.java_types.get(entity['name'].split('::', 1)[0]) or {}).get('attributes') or {}
            endpoint_id = context.add_resource('endpoint', f'GRAPHQL {type_name}.{field}', {
                'http_method': 'GRAPHQL', 'path': f'{type_name}.{field}', 'protocol': 'graphql',
                'operation_type': type_name.lower(), 'http_path': http_path, 'handler': handler,
                'arguments': schema_field.get('args') or [
                    {'name': p.get('name'), 'type': p.get('type')} for p in attributes.get('params') or []],
                'response_type': schema_field.get('returns') or attributes.get('return_type'),
                'summary': schema_field.get('description') or attributes.get('javadoc'),
                'security': self.security(attributes, owner), 'security_filter_chain': chain,
                'schema_file': self.schema_files.get((type_name, field)), 'external': False,
            }, file_path=path, start_line=int(entity.get('start_line') or 0))
            context.add_edge(endpoint_id, handler, 'handled_by')
            spring = context.framework_attributes(handler, 'spring')
            spring['endpoints'] = list(dict.fromkeys(list(spring.get('endpoints') or []) + [endpoint_id]))
            operations += 1
        for type_name in ROOT_TYPES:
            for field, info in self.schema.get(type_name, {}).items():
                if (type_name, field) in implemented:
                    continue
                context.add_resource('endpoint', f'GRAPHQL {type_name}.{field}', {
                    'http_method': 'GRAPHQL', 'path': f'{type_name}.{field}', 'protocol': 'graphql',
                    'operation_type': type_name.lower(), 'http_path': http_path, 'implemented': False,
                    'arguments': info.get('args'), 'response_type': info.get('returns'),
                    'summary': info.get('description'), 'external': False,
                    'schema_file': self.schema_files.get((type_name, field))},
                    file_path=self.schema_files.get((type_name, field), ''))
        context.shared['graphql'] = {'operations': operations, 'schema_types': len(self.schema)}


def enrich(context: EnrichmentContext) -> None:
    GraphQLEnricher(context).run()
